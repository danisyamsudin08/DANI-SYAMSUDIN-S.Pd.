export const SQL_SCHEMA_SCRIPT = `-- ========================================================
-- SKRIP DATABASE SUPABASE E-VOTING MAS & MBAK MOLAS 2026
-- SMP NEGERI 15 SEMARANG
-- Jalankan skrip ini di: Supabase Dashboard -> SQL Editor -> New Query
-- ========================================================

-- 1. TABEL PEMILIH (VOTERS)
CREATE TABLE IF NOT EXISTS public.voters (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    nama TEXT NOT NULL,
    kelas TEXT NOT NULL,
    status_voted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. TABEL KANDIDAT (CANDIDATES)
CREATE TABLE IF NOT EXISTS public.candidates (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    kategori TEXT NOT NULL CHECK (kategori IN ('mas', 'mbak')),
    nama TEXT NOT NULL,
    nomor_urut INTEGER NOT NULL,
    foto_url TEXT,
    visi_misi TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. TABEL SUARA (VOTES)
CREATE TABLE IF NOT EXISTS public.votes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    voter_id UUID NOT NULL REFERENCES public.voters(id) ON DELETE CASCADE,
    candidate_mas_id UUID NOT NULL REFERENCES public.candidates(id) ON DELETE RESTRICT,
    candidate_mbak_id UUID NOT NULL REFERENCES public.candidates(id) ON DELETE RESTRICT,
    voted_at TIMESTAMPTZ DEFAULT now(),
    CONSTRAINT unique_voter_vote UNIQUE (voter_id)
);

-- 4. AKTIFKAN ROW LEVEL SECURITY (RLS)
ALTER TABLE public.voters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.candidates ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.votes ENABLE ROW LEVEL SECURITY;

-- 5. KEBIJAKAN AKSES (POLICIES) UNTUK E-VOTING LUBER JURDIL
-- Izinkan pembacaan kandidat oleh publik (anon key)
CREATE POLICY "Public Read Candidates" ON public.candidates FOR SELECT TO anon USING (true);
CREATE POLICY "Admin All Candidates" ON public.candidates FOR ALL TO anon USING (true) WITH CHECK (true);

-- Kebijakan Akses Pemilih
CREATE POLICY "Public Voters Access" ON public.voters FOR ALL TO anon USING (true) WITH CHECK (true);

-- Kebijakan Akses Suara Masuk
CREATE POLICY "Public Votes Insert and Read" ON public.votes FOR ALL TO anon USING (true) WITH CHECK (true);

-- Sukses! Skrip ini telah siap digunakan bersama aplikasi e-voting.
`;
